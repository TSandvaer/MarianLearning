/**
 * Generate `packages/core/src/progress/canonMathFacts.generated.ts`: the
 * math fact of every problem in the committed Number Garden canon, per
 * step, in canon problem order (native spec
 * `design/native/review-mode-and-warmup-native.md` § 7.1).
 *
 * Core's review / warm-up picker (`reviewPlan.ts`) chooses canon blocks by
 * fact, and the server only copies the chosen blocks: `api/` can import
 * nothing from core but the import-free `wire/` modules, so the table has
 * to live in core. A fact is read exactly as the native app reads the plan
 * (`mathSessionPlanFromServer(plan, { extendedKinds: true })`): `{a, b, op}`
 * for arithmetic and multiplication (`2*3` and `3*2` are different facts),
 * `null` for number recognition and skip counting. The file of each step is
 * `canonFileTierFor`'s, the server's own wire→disk mapping
 * (`two-digit-addsub-no-regroup` → `two-digit-addsub.json`).
 *
 * `scripts/generateCanonMathFacts.test.ts` re-derives the table from the
 * canon files and fails when the committed module drifts, i.e. when a math
 * canon re-bake lands without a re-run of this script.
 *
 * Run: npx tsx scripts/generateCanonMathFacts.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { canonFilePath } from '../api/_canon.js'
import { mathSessionPlanFromServer } from '@marian/core/math/planFromServer'
import type { ExtendedMathProblem } from '@marian/core/math/extendedProblems'
import { MATH_TREE } from '@marian/core/progress/mastery'
import type { MathFact, NumberGardenNode } from '@marian/core/progress/types'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const CANON_ROOT = join(ROOT, 'public', 'canon')
export const OUT = join(
  ROOT,
  'packages',
  'core',
  'src',
  'progress',
  'canonMathFacts.generated.ts',
)

export type CanonMathFacts = Record<NumberGardenNode, (MathFact | null)[]>

/** A problem's fact, as `mobile/src/session/sessionEndPayload.ts` reads it. */
function problemFact(p: ExtendedMathProblem): MathFact | null {
  if (p.kind === 'arithmetic') return { a: p.addendA, b: p.addendB, op: p.op }
  if (p.kind === 'multiply') return { a: p.factorA, b: p.factorB, op: '*' }
  return null
}

/** The table, read from the canon files under `canonRoot`. */
export function deriveCanonMathFacts(
  canonRoot: string = CANON_ROOT,
): CanonMathFacts {
  const out = {} as CanonMathFacts
  for (const node of MATH_TREE) {
    const path = canonFilePath(canonRoot, {
      track: 'math',
      level: 1,
      focusNode: node,
    })
    const doc = JSON.parse(readFileSync(path, 'utf8')) as { plan: unknown }
    const plan = mathSessionPlanFromServer(doc.plan, { extendedKinds: true })
    out[node] = plan.problems.map(problemFact)
  }
  return out
}

function factLiteral(f: MathFact | null): string {
  return f === null ? 'null' : `{ a: ${f.a}, b: ${f.b}, op: '${f.op}' }`
}

/** The generated module's source. */
export function renderModule(facts: CanonMathFacts): string {
  const rows = MATH_TREE.map(
    (node) =>
      `  '${node}': [\n${facts[node].map((f) => `    ${factLiteral(f)},`).join('\n')}\n  ],`,
  ).join('\n')
  return `/**
 * GENERATED by \`scripts/generateCanonMathFacts.ts\` from
 * \`public/canon/math/level-1/*.json\`. Do not edit by hand: re-run
 * \`npx tsx scripts/generateCanonMathFacts.ts\` after a math canon re-bake.
 * \`scripts/generateCanonMathFacts.test.ts\` fails when this file drifts.
 *
 * The math fact of each canon problem (8 per step, in canon problem
 * order): \`{a, b, op}\` for arithmetic and multiplication, \`null\` for
 * number recognition and skip counting. Read by \`./reviewPlan.ts\`.
 */
import type { MathFact, NumberGardenNode } from './types'

export const CANON_MATH_FACTS: Readonly<
  Record<NumberGardenNode, readonly (MathFact | null)[]>
> = {
${rows}
}
`
}

function main(): void {
  writeFileSync(OUT, renderModule(deriveCanonMathFacts()))
  console.log(`wrote ${OUT}`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main()
}
